def parse_orga_repos(json_content: str) -> Dict[str, Dict[str, Any]]:
    """
    Parses a JSON string of Gitea repositories and organizes them into a dictionary.

    Args:
        json_content: A string containing the JSON response from the Gitea API,
                      representing a list of repositories.

    Returns:
        A dictionary where keys are repository names and values are dictionaries
        containing details like 'clone_url', 'ssh_url', etc.
    """
    orga_repos = {}
    repo_list: List[Dict[str, Any]] = json.loads(json_content)
    for repo in repo_list:
        orga_repos[repo['name']] = {
            'clone_url': repo.get('clone_url')
        }
    return orga_repos

